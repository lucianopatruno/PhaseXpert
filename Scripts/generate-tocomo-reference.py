#!/usr/bin/env python3
"""Generate reference results for the Swift ToCoMo port from the original Python code.

Run it with a Python environment that has the pinned `tocomo` package installed,
for example the AcidWatch worker environment:

    cd <acidwatch>/workers/tocomo && uv sync
    <acidwatch>/workers/tocomo/.venv/bin/python Scripts/generate-tocomo-reference.py

It writes PhaseXpertCore/Tests/PhaseXpertCoreTests/ToCoMoReferenceData.swift.
The package is MIT licensed (Copyright (c) 2025 Equinor):
https://github.com/equinor/tocomo  (pinned commit below).
"""

from __future__ import annotations

import contextlib
import io
import json
import sys
from pathlib import Path

from tocomo.reactions import Molecule, run_model_sm1

PINNED_COMMIT = "74e23131bd27d63dcf71b4a62eb81cdb76d981c9"

# name -> initial ppm. Only the five species PhaseXpert accepts as input.
CASES: list[tuple[str, dict[str, float]]] = [
    ("acidwatch-test-case", {"H2O": 40, "O2": 15, "SO2": 0, "NO2": 15, "H2S": 3}),
    ("all-zero", {"H2O": 0, "O2": 0, "SO2": 0, "NO2": 0, "H2S": 0}),
    ("no-reaction-no-reactants-in-reach", {"H2O": 0, "O2": 0, "SO2": 0, "NO2": 10, "H2S": 0}),
    ("cutoff-skips-small-reaction", {"H2O": 10, "O2": 10, "SO2": 0, "NO2": 0.01, "H2S": 0.0005}),
    ("sulfur-exact-stoichiometry", {"H2O": 0, "O2": 4, "SO2": 0, "NO2": 0, "H2S": 8}),
    ("sulfur-with-excess-oxygen", {"H2O": 0, "O2": 100, "SO2": 0, "NO2": 0, "H2S": 10}),
    ("sulfuric-acid-from-so2", {"H2O": 20, "O2": 0, "SO2": 5, "NO2": 5, "H2S": 0}),
    ("nitrogen-cycle-only", {"H2O": 200, "O2": 100, "SO2": 0, "NO2": 100, "H2S": 0}),
    ("oxygen-limited", {"H2O": 200, "O2": 2, "SO2": 0, "NO2": 100, "H2S": 0}),
    ("water-limited", {"H2O": 5, "O2": 1000, "SO2": 20, "NO2": 50, "H2S": 20}),
    ("mixed-high", {"H2O": 1000, "O2": 500, "SO2": 200, "NO2": 300, "H2S": 100}),
    ("fractional-inputs", {"H2O": 33.3, "O2": 7.7, "SO2": 1.25, "NO2": 12.5, "H2S": 2.75}),
]


def run_case(initial: dict[str, float]) -> dict:
    start = {Molecule[name]: value for name, value in initial.items()}
    # The reference prints one line per reaction step; keep stdout clean.
    with contextlib.redirect_stdout(io.StringIO()):
        result = run_model_sm1(start)
    return {
        "final": {m.name: result.final.get(m, 0.0) for m in Molecule},
        "steps": [
            {
                "reaction": step.reaction_index,
                "multiplier": step.multiplier,
                "after": {m.name: step.posterior.get(m, 0.0) for m in Molecule},
            }
            for step in result.steps
        ],
    }


def main() -> None:
    cases = []
    for name, initial in CASES:
        outcome = run_case(initial)
        cases.append({"name": name, "input": initial, **outcome})

    payload = json.dumps(
        {"commit": PINNED_COMMIT, "cases": cases}, indent=1, sort_keys=True
    )
    root = Path(__file__).resolve().parent.parent
    target = (
        root / "PhaseXpertCore" / "Tests" / "PhaseXpertCoreTests" / "ToCoMoReferenceData.swift"
    )
    target.write_text(
        "// Generated by Scripts/generate-tocomo-reference.py. Do not edit.\n"
        "// Source: https://github.com/equinor/tocomo (MIT, Copyright (c) 2025 Equinor)\n"
        f"// Pinned commit: {PINNED_COMMIT}\n"
        "// Re-run the script only when deliberately moving to a new reference commit.\n\n"
        "enum ToCoMoReferenceData {\n"
        '    static let json = #"""\n'
        f"{payload}\n"
        '"""#\n'
        "}\n"
    )
    print(f"Wrote {target} with {len(cases)} cases.", file=sys.stderr)


if __name__ == "__main__":
    main()
